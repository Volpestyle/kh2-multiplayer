"""Copy actual practice05 client events and queued claim keys, no live reads.
Historical logs lack applySeq; compiled controls establish it with callbacks.
"""
import argparse
import hashlib
import json
import re
import tempfile
from pathlib import Path
from companion_retained_fixture import fields, generate


def client_fixture(log, out):
    lines = log.read_text(encoding='utf-8').splitlines()
    parts, provenance, keys = [], [], []
    for index, seq in enumerate((7, 9)):
        selected = [line for line in lines if ('[hittrace]' in line or '[damagepolicy]' in line)
                    and fields(line).get('seq') == str(seq)]
        policy = next(fields(line) for line in selected if '[damagepolicy] event ' in line)
        event = next(fields(line) for line in selected if '[hittrace] context ' in line
                     and fields(line).get('phase') == '0')
        claims = [fields(line) for line in lines if '[client-claims]' in line
                  and fields(line).get('action') == 'submitted'
                  and fields(line).get('frame') == event['frame']]
        assert len(claims) == 1
        claim = claims[0]
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp)/'copied.log'
            source.write_text('\n'.join(re.sub(r'\bseq='+str(seq)+r'\b', 'seq=1', line)
                                        for line in selected)+'\n', encoding='utf-8')
            dest = Path(tmp)/'fixture.hpp'
            generate([source], dest)
            text = dest.read_text(encoding='utf-8')
        body = text.split('case 0: {', 1)[1].split('return e;}', 1)[0]
        # Restore the actual event token; child parent comes from real callbacks.
        body = body.replace('e.sequence=1;', 'e.sequence='+str(seq)+';', 1)
        body += 'p.zeroResult=static_cast<kh2coop::inject::damagepolicy::ZeroResult>('+policy['zeroResult']+');\n'
        parts.append('case '+str(index)+': {'+body+'return e;}')
        hit = next(fields(line) for line in selected if '[hittrace] input ' in line
                   and fields(line).get('phase') == '0')
        keys.append('case '+str(index)+': return {'+','.join(claim[k] for k in
                    ('claimRequester','claimSeq','epoch','claimNetId','claimObjectId'))+','+hit['attackId']+','+hit['damage']+'};')
        provenance.append(dict(case=index, event=seq, log=log.name,
                               sha256=hashlib.sha256(log.read_bytes()).hexdigest(),
                               claim=claim, copiedPolicy=policy))
    out.write_text('// Generated by practice_client_retained_fixture.py.\n'
                   'inline ht::Event RetainedPracticeClient(unsigned index){ht::Event e{};switch(index){\n'
                   +'\n'.join(parts)+'\ndefault:return e;}}\n'
                   'inline cc::Key RetainedPracticeClientKey(unsigned index){switch(index){\n'
                   +'\n'.join(keys)+'\ndefault:return {};}}\n', encoding='utf-8')
    out.with_suffix('.json').write_text(json.dumps(provenance, indent=2)+'\n', encoding='utf-8')


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('log', type=Path)
    p.add_argument('--out', type=Path, required=True)
    a = p.parse_args()
    client_fixture(a.log, a.out)
