"""VUH-2617 lead #301: the no-clip twin of a Thorn scenario, for bld.

Usage: make_noclip.py SCENARIO.json [--check]
Writes SCENARIO_noclip.json beside it: the same scenario minus every `clip` / `clip_wait` step and every fight step's
`clips`, with `_noclip` on its name and a description prefix. Nothing else changes. On bld (RTX 3080) two KH2s recording
30 fps clips during the fight dropped to 17-40 fps and the replay scored in the weak band; without clips it held 60 fps
(tools/rig/bld/README.md, docs/testing/vuh2339-bld02-noclip-20261024/). --check exits 1 if the twin on disk differs
from what this would write.
"""
import json
import sys
from pathlib import Path

NOTE = ("NOCLIP (VUH-2617 lead #301, bld): {name} without its clip/clip_wait steps and fight clips, generated by "
        "tools/rig/thorn_pilot/make_noclip.py; otherwise identical. ")


def noclip(scenario):
    out = dict(scenario)
    out["name"] = scenario["name"] + "_noclip"
    out["description"] = NOTE.format(name=scenario["name"]) + scenario["description"]
    steps = []
    for step in scenario["steps"]:
        if step.get("do") in ("clip", "clip_wait"):
            continue
        steps.append({k: v for k, v in step.items() if not (k == "clips" and step.get("do") == "fight")})
    out["steps"] = steps
    return out


def main(argv):
    if len(argv) not in (2, 3) or (len(argv) == 3 and argv[2] != "--check"):
        print(__doc__)
        return 2
    src = Path(argv[1])
    target = src.with_name(src.stem + "_noclip.json")
    text = json.dumps(noclip(json.loads(src.read_text(encoding="utf-8"))), indent=2, ensure_ascii=False) + "\n"
    if len(argv) == 3:
        current = target.read_text(encoding="utf-8") if target.exists() else None
        ok = current is not None and current.replace("\r\n", "\n") == text
        print(f"{target}: {'up to date' if ok else 'STALE or missing'}")
        return 0 if ok else 1
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
